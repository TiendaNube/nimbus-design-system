import fs from "fs";
import path from "path";

const rootDir = path.resolve(__dirname, "..");
const nextRootDir = path.join(rootDir, "packages/react/src/next");
const outputFilePath = path.join(nextRootDir, "index.ts");

const compareAscii = (a: string, b: string): number => {
  if (a < b) return -1;
  if (a > b) return 1;
  return 0;
};

const extractNamedExports = (entryPath: string): string[] => {
  const source = fs.readFileSync(entryPath, "utf8");
  const exportedNames: string[] = [];
  const blockRegex = /export\s+(?:type\s+)?\{([^}]+)\}/g;
  let match = blockRegex.exec(source);
  while (match !== null) {
    const specifiers = match[1]
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean);
    for (const specifier of specifiers) {
      const aliasParts = specifier
        .replace(/^type\s+/, "")
        .split(/\s+as\s+/i)
        .map((s) => s.trim());
      const exportedIdentifier = aliasParts[aliasParts.length - 1];
      if (exportedIdentifier && exportedIdentifier !== "default") {
        exportedNames.push(exportedIdentifier);
      }
    }
    match = blockRegex.exec(source);
  }
  return exportedNames;
};

export const generateNextIndex = (targetNextDir: string = nextRootDir): string => {
  fs.mkdirSync(targetNextDir, { recursive: true });

  const componentDirs = fs
    .readdirSync(targetNextDir, { withFileTypes: true })
    .filter((dirent) => dirent.isDirectory())
    .map((dirent) => dirent.name)
    .filter((dirName) =>
      fs.existsSync(path.join(targetNextDir, dirName, "src", "index.ts"))
    )
    .sort(compareAscii);

  const seenExports = new Map<string, string>();
  for (const componentDir of componentDirs) {
    const entryPath = path.join(targetNextDir, componentDir, "src", "index.ts");
    const names = extractNamedExports(entryPath);
    for (const exportedName of names) {
      const previousOwner = seenExports.get(exportedName);
      if (previousOwner && previousOwner !== componentDir) {
        throw new Error(
          `Duplicate /next export "${exportedName}" detected in both "${previousOwner}" and "${componentDir}".`
        );
      }
      seenExports.set(exportedName, componentDir);
    }
  }

  const lines = [
    "// AUTO-GENERATED FILE — DO NOT EDIT MANUALLY.",
    "// Generated by .scripts/generate-next-index.ts",
    "",
  ];

  if (componentDirs.length === 0) {
    lines.push("export {};", "");
  } else {
    for (const componentDir of componentDirs) {
      lines.push(`export * from "./${componentDir}/src";`);
    }
    lines.push("");
  }

  const content = lines.join("\n");
  const targetFile = path.join(targetNextDir, "index.ts");
  const current = fs.existsSync(targetFile)
    ? fs.readFileSync(targetFile, "utf8")
    : null;

  if (current !== content) {
    fs.writeFileSync(targetFile, content, "utf8");
  }

  return content;
};

if (require.main === module) {
  generateNextIndex(nextRootDir);
  // eslint-disable-next-line no-console
  console.log(`Generated ${path.relative(rootDir, outputFilePath)}`);
}
